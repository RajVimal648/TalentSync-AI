def save_or_update_job_role(role_title, description, required_skills=''):
    """
    Saves or updates a job role and JD description in the database.
    """
    role_title = role_title.strip()
    description = description.strip()
    if not role_title or not description:
        return None

    pg_conn = get_postgres_connection()
    if pg_conn:
        try:
            cur = pg_conn.cursor()
            cur.execute('''
                INSERT INTO job_roles (role_title, description, required_skills)
                VALUES (%s, %s, %s)
                ON CONFLICT (role_title) DO UPDATE
                SET description = EXCLUDED.description, required_skills = EXCLUDED.required_skills
                RETURNING role_id, role_title, description;
            ''', (role_title, description, required_skills))
            saved = cur.fetchone()
            pg_conn.commit()
            cur.close()
            pg_conn.close()
            return dict(saved) if saved else None
        except Exception as e:
            print(f"[WARNING] Supabase save job_roles failed: {e}")
            if pg_conn: pg_conn.close()

    # SQLite Fallback
    conn = get_sqlite_connection()
    cur = conn.cursor()
    try:
        cur.execute('''
            INSERT INTO job_roles (role_title, description, required_skills)
            VALUES (?, ?, ?)
            ON CONFLICT (role_title) DO UPDATE
            SET description = excluded.description, required_skills = excluded.required_skills
        ''', (role_title, description, required_skills))
        conn.commit()
        cur.execute('SELECT role_id, role_title, description FROM job_roles WHERE role_title = ?', (role_title,))
        row = cur.fetchone()
        return dict(row) if row else None
    finally:
        conn.close()

