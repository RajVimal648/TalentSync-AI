# --- Save Resume & Analysis ---
def save_analysis(user_id, resume_filename, resume_text, target_role, match_score, tfidf_score, section_score, detected_skills, missing_skills):
    # Try Supabase PostgreSQL
    pg_conn = get_postgres_connection()
    if pg_conn:
        try:
            cur = pg_conn.cursor()
            resume_id = None
            if resume_text:
                cur.execute(
                    'INSERT INTO resumes (user_id, filename, raw_text) VALUES (%s, %s, %s) RETURNING resume_id;',
                    (user_id, resume_filename or 'resume.txt', resume_text)
                )
                res = cur.fetchone()
                resume_id = res['resume_id'] if res else None

            detected_json = json.dumps(detected_skills if isinstance(detected_skills, list) else [])
            missing_json = json.dumps(missing_skills if isinstance(missing_skills, list) else [])

            cur.execute('''
                INSERT INTO analyses (user_id, resume_id, target_role, match_score, tfidf_score, section_score, detected_skills, missing_skills)
                VALUES (%s, %s, %s, %s, %s, %s, %s::jsonb, %s::jsonb)
                RETURNING analysis_id;
            ''', (user_id, resume_id, target_role, match_score, tfidf_score, section_score, detected_json, missing_json))

            res_analysis = cur.fetchone()
            analysis_id = res_analysis['analysis_id'] if res_analysis else None
            pg_conn.commit()
            cur.close()
            pg_conn.close()
            return analysis_id
        except Exception as e:
            print(f"[WARNING] Supabase save analysis failed: {e}. Falling back to SQLite.")
            if pg_conn: pg_conn.close()

    # SQLite Fallback
    conn = get_sqlite_connection()
    cur = conn.cursor()
    try:
        resume_id = None
        if resume_text:
            cur.execute(
                'INSERT INTO resumes (user_id, filename, raw_text) VALUES (?, ?, ?)',
                (user_id, resume_filename or 'resume.txt', resume_text)
            )
            resume_id = cur.lastrowid

        cur.execute('''
            INSERT INTO analyses (user_id, resume_id, target_role, match_score, tfidf_score, section_score, detected_skills, missing_skills)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            user_id,
            resume_id,
            target_role,
            match_score,
            tfidf_score,
            section_score,
            json.dumps(detected_skills),
            json.dumps(missing_skills)
        ))
        analysis_id = cur.lastrowid
        conn.commit()
        return analysis_id
    finally:
        conn.close()

# --- Get Scan History ---
def get_analysis_history(user_id=None, limit=50):
    # Try Supabase PostgreSQL
    pg_conn = get_postgres_connection()
    if pg_conn:
        try:
            cur = pg_conn.cursor()
            if user_id:
                cur.execute('''
                    SELECT analysis_id, user_id, resume_id, target_role, match_score, tfidf_score, section_score, 
                           detected_skills, missing_skills, analyzed_at
                    FROM analyses
                    WHERE user_id = %s
                    ORDER BY analyzed_at DESC LIMIT %s;
                ''', (user_id, limit))
            else:
                cur.execute('''
                    SELECT analysis_id, user_id, resume_id, target_role, match_score, tfidf_score, section_score, 
                           detected_skills, missing_skills, analyzed_at
                    FROM analyses
                    ORDER BY analyzed_at DESC LIMIT %s;
                ''', (limit,))

            rows = cur.fetchall()
            cur.close()
            pg_conn.close()

            history = []
            for row in rows:
                item = dict(row)
                if isinstance(item.get('detected_skills'), str):
                    try: item['detected_skills'] = json.loads(item['detected_skills'])
                    except Exception: item['detected_skills'] = []
                if isinstance(item.get('missing_skills'), str):
                    try: item['missing_skills'] = json.loads(item['missing_skills'])
                    except Exception: item['missing_skills'] = []
                if item.get('analyzed_at'):
                    item['analyzed_at'] = str(item['analyzed_at']).split('.')[0]
                history.append(item)
            return history
        except Exception as e:
            print(f"[WARNING] Supabase history failed: {e}. Falling back to SQLite.")
            if pg_conn: pg_conn.close()

    # SQLite Fallback
    conn = get_sqlite_connection()
    cur = conn.cursor()
    if user_id:
        cur.execute('''
            SELECT analysis_id, user_id, resume_id, target_role, match_score, tfidf_score, section_score, 
                   detected_skills, missing_skills, analyzed_at
            FROM analyses
            WHERE user_id = ?
            ORDER BY analyzed_at DESC LIMIT ?
        ''', (user_id, limit))
    else:
        cur.execute('''
            SELECT analysis_id, user_id, resume_id, target_role, match_score, tfidf_score, section_score, 
                   detected_skills, missing_skills, analyzed_at
            FROM analyses
            ORDER BY analyzed_at DESC LIMIT ?
        ''', (limit,))
    
    rows = cur.fetchall()
    conn.close()

    history = []
    for row in rows:
        item = dict(row)
        try:
            item['detected_skills'] = json.loads(item['detected_skills']) if item['detected_skills'] else []
        except Exception:
            item['detected_skills'] = []
        try:
            item['missing_skills'] = json.loads(item['missing_skills']) if item['missing_skills'] else []
        except Exception:
            item['missing_skills'] = []
        history.append(item)
    return history

# --- Delete Single Analysis ---
def delete_analysis(analysis_id, user_id=None):
    # Try Supabase PostgreSQL
    pg_conn = get_postgres_connection()
    if pg_conn:
        try:
            cur = pg_conn.cursor()
            if user_id:
                cur.execute('DELETE FROM analyses WHERE analysis_id = %s AND user_id = %s;', (analysis_id, user_id))
            else:
                cur.execute('DELETE FROM analyses WHERE analysis_id = %s;', (analysis_id,))
            pg_conn.commit()
            cur.close()
            pg_conn.close()
            return True
        except Exception as e:
            print(f"[WARNING] Supabase delete failed: {e}")
            if pg_conn: pg_conn.close()

    # SQLite Fallback
    conn = get_sqlite_connection()
    cur = conn.cursor()
    if user_id:
        cur.execute('DELETE FROM analyses WHERE analysis_id = ? AND user_id = ?', (analysis_id, user_id))
    else:
        cur.execute('DELETE FROM analyses WHERE analysis_id = ?', (analysis_id,))
    conn.commit()
    conn.close()
    return True

