-- TalentSync AI - Supabase PostgreSQL Schema
-- Run this script in the Supabase Dashboard -> SQL Editor

-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Resumes Table
CREATE TABLE IF NOT EXISTS public.resumes (
    resume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(user_id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    raw_text TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Analyses Table
CREATE TABLE IF NOT EXISTS public.analyses (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(user_id) ON DELETE SET NULL,
    resume_id BIGINT REFERENCES public.resumes(resume_id) ON DELETE SET NULL,
    target_role TEXT NOT NULL,
    match_score INTEGER NOT NULL,
    tfidf_score INTEGER NOT NULL,
    section_score INTEGER NOT NULL,
    detected_skills JSONB DEFAULT '[]'::jsonb,
    missing_skills JSONB DEFAULT '[]'::jsonb,
    analyzed_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resumes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analyses ENABLE ROW LEVEL SECURITY;

-- 5. Policies for anon/service access
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow all access on users') THEN
        CREATE POLICY "Allow all access on users" ON public.users FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow all access on resumes') THEN
        CREATE POLICY "Allow all access on resumes" ON public.resumes FOR ALL USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow all access on analyses') THEN
        CREATE POLICY "Allow all access on analyses" ON public.analyses FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;

